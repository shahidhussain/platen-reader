#!/usr/bin/env python3
"""Makes Platen Reader's third-party notices from one list.

Reads Licenses/components.json (every third-party component, with its
version, licence, copyright notice, source and how it is included) and the
licence texts in Licenses/texts/, and writes:

  THIRD_PARTY_LICENSES.md                 for people reading the repository
  PlatenReader/Shared/Acknowledgements.json
                                          bundled in both apps; About >
                                          Acknowledgements shows it

When a dependency is added, removed or updated: change components.json (and
add its licence text to Licenses/texts/ if it is a new one), then run

  python3 scripts/make-acknowledgements.py

and commit all three. `--check` writes nothing and fails if either output is
out of date (CI can run it).
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "Licenses" / "components.json"
TEXTS = ROOT / "Licenses" / "texts"
MARKDOWN = ROOT / "THIRD_PARTY_LICENSES.md"
BUNDLED = ROOT / "PlatenReader" / "Shared" / "Acknowledgements.json"


def build():
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    components = manifest["components"]
    texts = {}
    for c in components:
        name = c["text"]
        if name not in texts:
            texts[name] = (TEXTS / name).read_text(encoding="utf-8").strip() + "\n"

    # The bundled file: each component, and each licence text once.
    bundled = {
        "components": [
            {key: c[key] for key in ("name", "version", "licence", "notice", "source", "shipped", "text")}
            for c in components
        ],
        "texts": texts,
        "notes": manifest["notes"],
    }
    bundled_text = json.dumps(bundled, indent=1, ensure_ascii=False, sort_keys=True) + "\n"

    # The Markdown: the audit table, the notes, then each licence in full.
    lines = [
        "# Third-party licences",
        "",
        "Platen Reader is released under the Mozilla Public License 2.0 (LICENSE).",
        "It includes the third-party components below. This file is generated by",
        "`scripts/make-acknowledgements.py` from `Licenses/components.json`; edit",
        "that, not this. The apps show the same list in About › Acknowledgements.",
        "",
    ]
    for shipped, heading in (("app", "In the macOS and iOS apps"),
                             ("voice", "In the natural-voice pack (downloaded only when the reader asks)")):
        lines += [f"## {heading}", "",
                  "| Component | Version | Licence | Source | How it is included |",
                  "| --- | --- | --- | --- | --- |"]
        for c in components:
            if c["shipped"] != shipped:
                continue
            cells = [c["name"], c["version"], c["licence"], c["source"], c["included"]]
            lines.append("| " + " | ".join(cell.replace("|", "\\|") for cell in cells) + " |")
        lines.append("")
    lines += ["## Notes", ""] + [f"- {note}" for note in manifest["notes"]] + [""]
    lines += ["## Notices and licence texts", ""]
    for c in components:
        lines += [f"### {c['name']}", "", c["notice"], "", f"Licence: {c['licence']} (text: {c['text']})", ""]
    for name, text in texts.items():
        lines += [f"### {name}", "", "```text", text.rstrip("\n"), "```", ""]
    markdown_text = "\n".join(lines)
    return markdown_text, bundled_text


def main():
    markdown_text, bundled_text = build()
    if "--check" in sys.argv:
        stale = [p.name for p, t in ((MARKDOWN, markdown_text), (BUNDLED, bundled_text))
                 if not p.exists() or p.read_text(encoding="utf-8") != t]
        if stale:
            sys.exit("Out of date (run scripts/make-acknowledgements.py): " + ", ".join(stale))
        print("Third-party notices are up to date.")
        return
    MARKDOWN.write_text(markdown_text, encoding="utf-8")
    BUNDLED.write_text(bundled_text, encoding="utf-8")
    print(f"Wrote {MARKDOWN.relative_to(ROOT)} and {BUNDLED.relative_to(ROOT)}.")


if __name__ == "__main__":
    main()
