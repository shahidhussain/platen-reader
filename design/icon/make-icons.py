#!/usr/bin/env python3
"""Generates the Platen icon (concept D, "Spread") in several background
colours, plus a comparison sheet. Original artwork, MPL-2.0 with the app.

The design: an open book, two columns of text in a two-page spread, rising
out of a typewriter platen at the bottom, with Platen's red bookmark ribbon
hanging from the top edge of the right-hand page.

Usage: python3 design/icon/make-icons.py   (writes into design/icon/)
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))

# Background gradients, top to bottom. "amber" is concept B's yellow; the
# rest are progressively lighter.
BACKGROUNDS = {
    "amber": ("#e9b45c", "#c9772f"),
    "honey": ("#f4cf7e", "#e0a24c"),
    "butter": ("#fbe3a2", "#f0c36a"),
    "cream": ("#fdf0cf", "#f3d9a0"),
    "apricot": ("#fcd9b0", "#f2ae78"),
}


def icon(name, top, bottom):
    p = name  # id prefix, so several icons can share one SVG document
    left_lines = [236, 212, 236, 186, 224, 236, 170]
    right_lines = [236, 220, 236, 200, 236, 228, 150]
    lines = []
    for i, w in enumerate(left_lines):
        lines.append(f'<rect x="286" y="{318 + i * 44}" width="{w - 50}" height="16" rx="8"/>')
    for i, w in enumerate(right_lines):
        # leave room for the ribbon at the top of the right-hand page
        if i < 3:
            w = min(w, 178)  # stop just short of the ribbon
        lines.append(f'<rect x="548" y="{318 + i * 44}" width="{w - 50}" height="16" rx="8"/>')
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">
  <!-- Platen Reader icon, "Spread" on {name}. Generated by make-icons.py. -->
  <defs>
    <linearGradient id="{p}-bg" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="{top}"/>
      <stop offset="1" stop-color="{bottom}"/>
    </linearGradient>
    <linearGradient id="{p}-paper" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#fffdf8"/>
      <stop offset="1" stop-color="#f3ead7"/>
    </linearGradient>
    <!-- shading at the spine, where the two pages meet -->
    <linearGradient id="{p}-spine" x1="0" y1="0" x2="1" y2="0">
      <stop offset="0" stop-color="#7a5a2a" stop-opacity="0"/>
      <stop offset="0.5" stop-color="#7a5a2a" stop-opacity="0.22"/>
      <stop offset="1" stop-color="#7a5a2a" stop-opacity="0"/>
    </linearGradient>
    <linearGradient id="{p}-roller" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#14181e"/>
      <stop offset="0.28" stop-color="#525a66"/>
      <stop offset="0.42" stop-color="#2b313a"/>
      <stop offset="1" stop-color="#0a0c10"/>
    </linearGradient>
    <linearGradient id="{p}-knob" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#a3acb7"/>
      <stop offset="1" stop-color="#434a54"/>
    </linearGradient>
    <!-- Two shadows: a tight one that defines the paper's edges against the
         background, and a soft, wider one that lifts it off. -->
    <filter id="{p}-shadow" x="-25%" y="-25%" width="150%" height="160%">
      <feDropShadow dx="0" dy="3" stdDeviation="4" flood-color="#4a2600" flood-opacity="0.45" result="edge"/>
      <feGaussianBlur in="SourceAlpha" stdDeviation="28" result="blur"/>
      <feOffset in="blur" dy="22" result="offset"/>
      <feFlood flood-color="#4a2600" flood-opacity="0.45"/>
      <feComposite in2="offset" operator="in" result="soft"/>
      <feMerge>
        <feMergeNode in="soft"/>
        <feMergeNode in="edge"/>
      </feMerge>
    </filter>
  </defs>
  <rect x="100" y="100" width="824" height="824" rx="185" fill="url(#{p}-bg)"/>
  <!-- the open book: two pages, side by side -->
  <g filter="url(#{p}-shadow)">
    <rect x="248" y="250" width="528" height="430" rx="6" fill="url(#{p}-paper)"/>
  </g>
  <rect x="248.5" y="250.5" width="527" height="429" rx="6" fill="none" stroke="#b08a50" stroke-opacity="0.25"/>
  <rect x="482" y="250" width="60" height="430" fill="url(#{p}-spine)"/>
  <g fill="#c4b597">
    {"".join(lines)}
  </g>
  <!-- bookmark ribbon, hanging from the top of the right-hand page -->
  <path d="M690 250 L734 250 L734 384 L712 362 L690 384 Z" fill="#d0342c"/>
  <!-- the platen (roller) at the bottom, with its knobs -->
  <rect x="226" y="648" width="572" height="120" rx="60" fill="url(#{p}-roller)"/>
  <rect x="262" y="670" width="500" height="9" rx="4.5" fill="#ffffff" opacity="0.2"/>
  <rect x="170" y="656" width="78" height="104" rx="30" fill="url(#{p}-knob)"/>
  <rect x="776" y="656" width="78" height="104" rx="30" fill="url(#{p}-knob)"/>
</svg>
'''


def ios_icon(svg):
    """The iOS and iPadOS version of an icon. iOS draws the rounded corners
    itself and wants a full-bleed, opaque square, so the background fills the
    whole 1024 square and the artwork is scaled up from the Mac icon's
    824-pixel rounded square (100 to 924) to fill it."""
    svg = re.sub(r'<rect x="100" y="100" width="824" height="824" rx="185" (fill="[^"]*")/>',
                 r'<rect width="1024" height="1024" \1/>', svg)
    head, rest = svg.split("</defs>", 1)
    body, tail = rest.rsplit("</svg>", 1)
    scale = 1024 / 824
    background, art = body.split("/>", 1)
    return (f'{head}</defs>{background}/>\n  <g transform="scale({scale:.6f}) translate(-100 -100)">'
            f'{art}  </g>\n</svg>{tail}')


def sheet(names):
    """All variants at full size and at 128, 64, 32 and 16 points, on light
    and dark backgrounds."""
    inner = {}
    for n in names:
        t = open(os.path.join(HERE, f"spread-{n}.svg")).read()
        inner[n] = re.sub(r"^.*?<svg[^>]*>", "", t, flags=re.S).rsplit("</svg>", 1)[0]
    W = H = 1500
    col = W // len(names)
    font = 'font-family="-apple-system, Helvetica"'
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}">',
           f'<rect width="{W}" height="{H}" fill="#f4f4f6"/>',
           f'<rect y="1050" width="{W}" height="450" fill="#1e1e20"/>']
    big = col - 30
    for i, n in enumerate(names):
        x = i * col + 15
        out.append(f'<svg x="{x}" y="60" width="{big}" height="{big}" viewBox="0 0 1024 1024">{inner[n]}</svg>')
        out.append(f'<text x="{x + big // 2}" y="{60 + big + 40}" {font} font-size="28" font-weight="600" '
                   f'text-anchor="middle" fill="#222">{n.capitalize()}</text>')
        for y in (520, 1110):
            sizes = (128, 64, 32, 16)
            cy = y
            for size in sizes:
                out.append(f'<svg x="{x + (big - size) // 2}" y="{cy}" width="{size}" height="{size}" '
                           f'viewBox="0 0 1024 1024">{inner[n]}</svg>')
                cy += size + 22
    out.append(f'<text x="750" y="1030" {font} font-size="22" text-anchor="middle" fill="#666">'
               'Sizes 128, 64, 32 and 16 points on light, and below on dark</text>')
    out.append("</svg>")
    open(os.path.join(HERE, "spread-comparison.svg"), "w").write("\n".join(out))


if __name__ == "__main__":
    for name, (top, bottom) in BACKGROUNDS.items():
        open(os.path.join(HERE, f"spread-{name}.svg"), "w").write(icon(name, top, bottom))
    sheet(list(BACKGROUNDS))
    # iOS uses Honey, like the Mac. Render it to a PNG with Quick Look, then
    # flatten it (iOS icons must have no transparency):
    #   qlmanage -t -s 1024 -o /tmp design/icon/spread-honey-ios.svg
    #   python3 -c "from PIL import Image; Image.open('/tmp/spread-honey-ios.svg.png')\
    #     .convert('RGB').save('PlatenReader iOS/Sources/Assets.xcassets/AppIcon.appiconset/AppIcon-1024.png')"
    honey = icon("honey", *BACKGROUNDS["honey"])
    open(os.path.join(HERE, "spread-honey-ios.svg"), "w").write(ios_icon(honey))
    print("wrote", ", ".join(f"spread-{n}.svg" for n in BACKGROUNDS),
          "spread-comparison.svg and spread-honey-ios.svg")
